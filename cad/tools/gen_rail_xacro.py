#!/usr/bin/env python3
"""Generate z1_ext_gazebo/urdf/rail.xacro from the whole12 CAD parts.

Inputs : cad/whole12/*.stl (parts in their own frames, mm) and
         cad/whole12_placements.json (part placements in the assembly frame, mm,
         solved by place_parts.py and checked to rebuild 00_full_assembly.stl exactly).
Output : rail.xacro on stdout.
Needs  : numpy, trimesh (only to regenerate; not needed at runtime).
"""
import json, os, sys
import numpy as np, trimesh

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # cad/
PARTS = os.path.join(ROOT, 'whole12')
PL = json.load(open(os.path.join(ROOT, 'whole12_placements.json')))

# Which link each part instance belongs to.  The carriage-side drag-chain block is the
# instance hanging under the carriage plate (z = 24 mm); the other one sits in the trough.
MOVING = {'04_runner', '05_carriage_plate', '06_steel_plate', '09_pinion_disc', '10_pinion_pin'}
def is_moving(name, t): return name in MOVING or (name == '13_chain_block' and t[2] == 24.0)

# Parts that get collision geometry.  Left out on purpose:
#  - runners: they ride the dovetail rails with ~0.3 mm clearance; mesh contact there would
#    drag/jam.  The prismatic joint does the guiding.
#  - pinion discs/pins: they mesh with the rack (and, in this CAD, also cut into rail strip #0).
#  - carriage chain block: in this CAD it intersects rail #1 (~1140 mm^3).
NO_COLLISION = {'04_runner', '09_pinion_disc', '10_pinion_pin'}
def has_collision(name, t): return name not in NO_COLLISION and not (name == '13_chain_block' and is_moving(name, t))

# Assumed densities (kg/m^3) -- material is not in the CAD.
STEEL, ALU, MDF, PLASTIC = 7850.0, 2700.0, 750.0, 1200.0
DENSITY = {'01_base_board': MDF, '02_rail_strip': ALU, '03_rail': ALU, '04_runner': ALU,
           '05_carriage_plate': ALU, '06_steel_plate': STEEL, '07_rack': STEEL,
           '08_rack_spacer': ALU, '09_pinion_disc': STEEL, '10_pinion_pin': STEEL,
           '11_trough_floor': ALU, '12_trough_side': ALU, '13_chain_block': PLASTIC,
           '14_hard_stop': ALU}
COLOR = {'01_base_board': (0.55, 0.42, 0.28), '06_steel_plate': (0.45, 0.47, 0.50),
         '07_rack': (0.35, 0.36, 0.38), '09_pinion_disc': (0.35, 0.36, 0.38),
         '10_pinion_pin': (0.35, 0.36, 0.38), '13_chain_block': (0.10, 0.10, 0.10),
         '14_hard_stop': (0.80, 0.15, 0.10)}
DEFAULT_COLOR = (0.75, 0.76, 0.78)

def instances():
    for f, insts in sorted(PL.items()):
        name = f[:-4]
        for k, o in enumerate(insts):
            R = np.array(o['R'], dtype=float)
            assert np.allclose(R, np.eye(3)), f'{f}: only pure translations are expected'
            yield name, k, o['t_mm']

links = {'rail_base': [], 'carriage': []}
for name, k, t in instances():
    m = trimesh.load(os.path.join(PARTS, name + '.stl'))
    assert m.is_watertight and m.volume > 0, name
    m.apply_translation(t)
    m.apply_scale(0.001)                     # mm -> m
    m.density = DENSITY[name]
    links['carriage' if is_moving(name, t) else 'rail_base'].append((name, k, t, m))

def mass_props(items):
    total = sum(m.mass for *_, m in items)
    com = sum(m.mass * m.center_mass for *_, m in items) / total
    I = np.zeros((3, 3))
    for *_, m in items:  # parallel-axis shift of each part's inertia to the common COM
        d = m.center_mass - com
        I += m.moment_inertia + m.mass * (np.dot(d, d) * np.eye(3) - np.outer(d, d))
    return total, com, I

f6 = lambda x: f'{x:.6g}'
out = ['<?xml version="1.0"?>',
       '<!-- GENERATED by cad/tools/gen_rail_xacro.py from cad/whole12. Do not edit by hand. -->',
       '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">',
       '  <!-- Link frames = CAD assembly frame (x along the rail, z up, z=0 = top of the base board).',
       '       rail_joint = 0 is the carriage position in 00_full_assembly.stl. -->']
for link, items in links.items():
    M, c, I = mass_props(items)
    out += [f'  <link name="{link}">',
            '    <inertial>',
            f'      <origin xyz="{f6(c[0])} {f6(c[1])} {f6(c[2])}" rpy="0 0 0"/>',
            f'      <mass value="{f6(M)}"/>',
            f'      <inertia ixx="{f6(I[0,0])}" ixy="{f6(I[0,1])}" ixz="{f6(I[0,2])}" iyy="{f6(I[1,1])}" iyz="{f6(I[1,2])}" izz="{f6(I[2,2])}"/>',
            '    </inertial>']
    for name, k, t, _ in items:
        xyz = ' '.join(f6(v / 1000.0) for v in t)
        col = ' '.join(str(v) for v in COLOR.get(name, DEFAULT_COLOR))
        geo = f'<geometry><mesh filename="package://z1_ext_gazebo/meshes/{name}.stl" scale="0.001 0.001 0.001"/></geometry>'
        out += [f'    <visual name="{name}_{k}">',
                f'      <origin xyz="{xyz}" rpy="0 0 0"/>', f'      {geo}',
                f'      <material name="{name}"><color rgba="{col} 1"/></material>',
                '    </visual>']
        if has_collision(name, t):
            out += [f'    <collision name="{name}_{k}">',
                    f'      <origin xyz="{xyz}" rpy="0 0 0"/>', f'      {geo}', '    </collision>']
    out.append('  </link>')
    print(f'{link}: mass {M:.3f} kg, com {np.round(c, 4)}', file=sys.stderr)
out.append('</robot>')
print('\n'.join(out))
